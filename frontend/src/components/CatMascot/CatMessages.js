// Message Picker Service helper
export const getRandomMessage = (type = 'normal', lastMessage = '') => {
  let list = NORMAL_MESSAGES;
  if (type === 'warning') {
    list = WORK_WARNING_MESSAGES;
  } else if (type === 'completed') {
    list = TASK_COMPLETED_MESSAGES;
  }

  // Filter out last message to avoid immediate repeating
  const available = list.filter(msg => msg !== lastMessage);
  const choices = available.length > 0 ? available : list;
  const randomIndex = Math.floor(Math.random() * choices.length);
  return choices[randomIndex];
};
